import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {createServer} from 'node:http';
import {connectDatabase,disconnectDatabase} from '../server/database.mjs';
import {createModels} from '../server/models.mjs';
import {createApp} from '../server/app.mjs';
test('payment approvals and reminders in an isolated database',async()=>{
 let db,server;
 try{
  const connection=await connectDatabase();db=connection.useDb('ttest_'+randomUUID().replaceAll('-',''));
  const models=createModels(db);for(const m of Object.values(models))await m.createIndexes();
  server=createServer(createApp(models,db,{allowLegacyLogin:true}));await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const base='http://127.0.0.1:'+server.address().port+'/api';
  const request=async(path,token,body)=>{const r=await fetch(base+path,{method:body===undefined?'GET':'POST',headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:body===undefined?undefined:JSON.stringify(body)});return {status:r.status,...await r.json()};};
  const a=await request('/session',null,{displayName:'Receiver'}),b=await request('/session',null,{displayName:'Payer'}),c=await request('/session',null,{displayName:'Outsider'});
  const {trip}=await request('/trips/create',a.token,{name:'Payment test'});await request('/trips/join',b.token,{joinCode:trip.joinCode});
  const root='/payments/trips/'+trip._id;
  await request('/expenses/sync',a.token,{offlineExpenses:[{tripId:trip._id,ledger:'personal',title:'Test meal',amountPaise:10000,splitAmong:[b.user._id],clientId:randomUUID(),clientCreatedAt:new Date().toISOString()}]});
  assert.equal((await request('/payments/profile',a.token,{upiId:'receiver@testbank'})).status,200);
  assert.equal((await request('/payments/profile',a.token,{upiId:'upi://bad?x=1'})).status,400);
  assert.equal((await request(root+'/recipient/'+a.user._id,b.token)).upiId,'receiver@testbank');
  assert.equal((await request(root+'/recipient/'+a.user._id,c.token)).status,404);
  assert.equal((await request('/trips/'+trip._id,b.token)).members.some(m=>'upiId'in m),false);
  assert.equal((await request(root+'/remind',a.token,{to:b.user._id,ledger:'personal'})).status,200);
  assert.equal((await request(root+'/remind',a.token,{to:b.user._id,ledger:'personal'})).status,429);
  const body={to:a.user._id,ledger:'personal',amountPaise:4000,clientId:randomUUID()};
  const created=await request(root+'/requests',b.token,body);assert.equal(created.status,200);
  assert.equal((await request(root+'/requests',b.token,body)).payment._id,created.payment._id);
  assert.equal((await request(root+'/requests',b.token,{...body,amountPaise:3000})).status,409);
  assert.equal((await request('/trips/'+trip._id,b.token)).transactions[0].amountPaise,10000);
  assert.equal((await request(root+'/requests/'+created.payment._id+'/accept',b.token,{})).status,403);
  assert.equal((await request(root+'/requests/'+created.payment._id+'/accept',c.token,{})).status,404);
  const approvals=await Promise.all([request(root+'/requests/'+created.payment._id+'/accept',a.token,{}),request(root+'/requests/'+created.payment._id+'/accept',a.token,{})]);
  assert.ok(approvals.every(r=>r.status===200));assert.equal((await request('/trips/'+trip._id,b.token)).transactions[0].amountPaise,6000);
  assert.equal(await models.Notification.countDocuments({kind:'accepted'}),1);
  const rejected=await request(root+'/requests',b.token,{...body,clientId:randomUUID(),amountPaise:2000});
  assert.equal((await request(root+'/requests/'+rejected.payment._id+'/reject',a.token,{})).status,200);
  assert.equal((await request('/trips/'+trip._id,b.token)).transactions[0].amountPaise,6000);
  assert.equal((await request(root+'/requests/'+rejected.payment._id+'/accept',a.token,{})).status,409);
  assert.equal((await request(root+'/requests',b.token,{...body,clientId:randomUUID(),amountPaise:7000})).status,409);
  await request('/trips/'+trip._id+'/end',a.token,{});
  const final=await request(root+'/requests',b.token,{...body,clientId:randomUUID(),amountPaise:6000});
  assert.equal(final.status,200);await request(root+'/requests/'+final.payment._id+'/accept',a.token,{});
  assert.deepEqual((await request('/trips/'+trip._id,b.token)).transactions,[]);
  assert.equal((await request('/notifications',c.token)).items.length,0);
  assert.ok((await request('/notifications',b.token)).items.some(n=>n.kind==='accepted'));
  assert.equal((await request(root+'/recipient/'+a.user._id,b.token)).status,403);
 }finally{if(server)await new Promise(resolve=>server.close(resolve));if(db)await db.dropDatabase();await disconnectDatabase();}
});
